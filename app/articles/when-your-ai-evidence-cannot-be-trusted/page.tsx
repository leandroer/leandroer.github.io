  "<h2>9. Build tamper-evident evidence collection</h2>",
  "<p>Centralized logs help responders correlate activity, but the evidence path also needs protection from unauthorized modification or deletion. CISA recommends centralizing logs, restricting access, storing them securely, and retaining them according to policy. <a href=\"https://www.cisa.gov/audiences/small-and-medium-businesses/secure-your-business/use-logging-on-business-systems\">CISA logging guidance</a></p>",
  "<p>For high-value AI events:</p>",
  "<ol>",
  "<li>Generate a unique event identifier at the source.</li>",
  "<li>Add trace, span, session, run, turn, and tool-call identifiers.</li>",
  "<li>Validate the event against a versioned schema.</li>",
  "<li>Canonicalize the security-relevant fields.</li>",
  "<li>Calculate a content digest.</li>",
  "<li>Link batches or events using a previous digest where appropriate.</li>",
  "<li>Send raw evidence to restricted storage.</li>",
  "<li>Send a redacted operational copy to detection systems.</li>",
  "<li>Periodically sign an export manifest.</li>",
  "<li>Store incident exports under immutable retention.</li>",
  "<li>Log every read, export, retention change, and deletion attempt.</li>",
  "</ol>",
